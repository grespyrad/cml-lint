#!/usr/bin/env python3
"""Embed the same grammar in the dependency-free C++ benchmark."""
import json
from pathlib import Path
root=Path(__file__).resolve().parents[1]
rules=json.loads((root/'bench/grammar/grammar.json').read_text())
nodes=[]
def visit(e):
    children=[visit(a) for a in e.get('args',[])]
    nodes.append((e['op'],e.get('text',''),children))
    return len(nodes)-1
indices={name:visit(r['expr']) for name,r in rules.items()}
literals=sorted({t for op,t,_ in nodes if op=='lit'},key=lambda s:(-len(s),s))
def quote(s):return json.dumps(s,ensure_ascii=False)
text='// Generated by scripts/compile_bench_grammar.py; do not edit.\n'
text+='const std::vector<Expr> expressions = {\n'+',\n'.join('{'+quote(op)+','+quote(t)+',{'+','.join(map(str,c))+'}}' for op,t,c in nodes)+'\n};\n'
text+='const std::unordered_map<std::string_view,int> rules = {'+','.join('{'+quote(n)+','+str(i)+'}' for n,i in indices.items())+'};\n'
text+='const std::vector<std::string_view> literals = {'+','.join(map(quote,literals))+'};\n'
(root/'bench/cpp/grammar.inc').write_text(text)
